def templates():
    return [k for k, _ in BUILDERS]


def _task(key, k, seed, b):
    intent, lesson = TEMPLATE_INTENT[key]
    tags = [TAG, "training", "source:ours", "intent:" + intent, key]
    if lesson:
        tags.append("lesson:" + lesson)
    if key in HOLDOUT_TEMPLATES:
        tags.append("holdout")
    judge = []
    if b.get("unchanged"):
        judge.append({"type": "files_unchanged", "paths": b["unchanged"]})
    judge.append({"type": "python_assert", "code": b["hidden"], "timeout": 90})
    if b.get("min_tests") and not b.get("already_tested"):
        judge.append({"type": "python_assert", "timeout": 30, "code": _sub(MIN_TESTS, {"n": b["min_tests"]})})
    if b.get("tests"):
        judge.append({"type": "tests_pass"})
    return {"id": f"{PREFIX}-{key}-s{seed}-{k:02d}", "template": key, "family": TAG, "lesson": lesson, "intent": intent, "tags": tags, "goal": b["goal"],
            "params": {"domains": ["api"]}, "fixture": {"files": b["fixture"]}, "budget": {"calls": 20, "tokens": 80000, "seconds": 1200}, "judge": judge,
            "solution": {"files": b["sol"]}, "wrong": {"files": b["wrong"]}}


def tasks_for(seed=0, per=PER_TEMPLATE, keys=None):
    """-> tasks, template by template: `per` DISTINCT variants of each (distinct by goal text). Pure and seed-stable."""
    out = []
    for key, fn in BUILDERS:
        if keys and key not in keys:
            continue
        seen, k, tries = set(), 0, 0
        while len(seen) < per and tries < per * 8:
            b = fn(random.Random(f"{seed}:ours:{key}:{k}"))
            tries += 1
            k += 1
            h = hashlib.sha1(b["goal"].encode()).hexdigest()
            if h in seen:
                continue
            seen.add(h)
            out.append(_task(key, k - 1, seed, b))
    return out


def all_tasks(seed=0):
    return tasks_for(seed)


def generate(n, seed=0):
    """n tasks, round-robin over the templates (a short run touches every request once), for this seed."""
    by = {}
    for t in tasks_for(seed):
        by.setdefault(t["template"], []).append(t)
    keys = sorted(by)
    random.Random(f"{seed}:{TAG}").shuffle(keys)
    out, i = [], 0
    while any(i < len(v) for v in by.values()):
        out += [by[k][i] for k in keys if i < len(by[k])]
        i += 1
    return out[:max(0, n)]


