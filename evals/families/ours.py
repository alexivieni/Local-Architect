def _dist():
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, here)
    import importlib.util
    spec = importlib.util.spec_from_file_location("ours_distributed", os.path.join(here, "distributed.py"))
    dist = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(dist)
    dist._setup_paths(isolate=True)
    return dist


def prove(tasks, say=print):
    """-> (failures, caught_count). The reference passes every judge and the wrong answer is caught by at least one."""
    dist = _dist()
    import arch_eval as E
    import arch_fakecode as F
    bad = 0
    for t in tasks:
        t = E.normalize(dict(t, flow=FLOW)) if "flow" not in t else t
        probs = E.validate(t)
        files = t["solution"]["files"]
        right, unit = dist._judge_all(E, t, files)
        wrong, _ = dist._judge_all(E, t, t["wrong"]["files"])
        bad_right = [(ty, why) for ty, good, why, could in right if not good or not could]
        caught = [ty for ty, good, why, could in wrong if not good and could]
        fake = [f"{rel}:{x['line']}" for rel, text in files.items() for x in F.scan_text(rel, text) if x.get("gate")]
        ok = not probs and not bad_right and not fake and bool(caught) and (unit[0] or t["fixture"]["files"].get("index.html") is not None or not any(
            n.startswith("tests/") for n in list(files) + list(t["fixture"]["files"])))
        bad += 0 if ok else 1
        say(f"  {'PASS' if ok else 'FAIL'}  {t['id']}" + ("" if ok else f"   {probs or bad_right or fake or ('not caught' if not caught else unit[1][-200:])}"))
    return bad


def check(quick=False, seed=0):
    tasks = all_tasks(seed)
    if quick:
        seen, pick = set(), []
        for t in tasks:
            if t["template"] not in seen:
                seen.add(t["template"])
                pick.append(t)
        tasks = pick
    bad = prove(tasks)
    print(f"\n{'ALL ' + str(len(tasks)) + ' OURS CHECKS PASSED' if not bad else str(bad) + ' of ' + str(len(tasks)) + ' OURS CHECKS FAILED'}")
    return 1 if bad else 0


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args(argv)
    if a.check:
        return check(a.quick, a.seed)
    for t in all_tasks(a.seed):
        print(f"  {t['id']:40} {str(t['lesson']):16} {t['goal'][:80]}")
    return 0


