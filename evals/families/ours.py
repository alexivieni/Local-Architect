def _sub(s, d):
    for k, v in d.items():
        s = s.replace("@" + k + "@", str(v))
    return s


def _voice(r, body):
    """The request in the person's casual voice: lower case, plain, no ceremony. Pure code templates."""
    return (r.choice(OPEN) + body[0].lower() + body[1:] + r.choice(CLOSE)).strip()


